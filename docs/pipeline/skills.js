const skillCatalog = new Map(Object.values(stageSkills).flatMap(group=>Object.entries(group)));

function composition(node,automatic=[]) {
  const group = Object.hasOwn(stageSkills,node.id) ? stageSkills[node.id] : {};
  const leadTask = Object.hasOwn(group,node.agent) ? group[node.agent] : node.description;
  const names = new Set([...automatic,...Object.keys(group),...(node.skills || [])]);
  names.delete(node.agent);
  return [
    {name:node.agent,task:leadTask,lead:true},
    ...Array.from(names,name=>({name,task:group[name] || routeTask(node.id,name) || skillCatalog.get(name) || "Подключается к задаче этапа.",lead:false}))
  ];
}

function routeTask(stage,skill) {
  if (stage==="build" && skill==="playwright") return "Запускает собранный Web-прототип в браузере и проверяет первый игровой раунд.";
  if (stage==="build" && skill==="game-mobile") return "Адаптирует управление и игровой экран к сенсорному устройству.";
  if (stage==="qa" || stage==="finish") {
    const tasks={
      "unity-mcp-orchestrator":"Открывает целевую сцену Unity и проверяет запуск сборки и ошибки в консоли.",
      "game-roblox":"Проверяет игру в Roblox Studio на клиенте и сервере, включая запуск и сброс раунда.",
      playwright:"Проверяет запуск передаваемой Web-сборки в браузере."
    };
    return tasks[skill];
  }
}

if (typeof module!=="undefined" && module.exports) module.exports={composition,skillCatalog};
